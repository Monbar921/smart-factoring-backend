package ru.smart.factoring.backend.api.risk;

/**
 * Событие ЕФРСБ / ЕГРЮЛ по покупателю для имитации подписки на мониторинг контрагентов (Р-86).
 * <ul>
 *     <li>INTENT - намерение кредитора обратиться в суд с заявлением о банкротстве: предупреждение, не стоп-фактор;</li>
 *     <li>OBSERVATION - введено наблюдение: стоп-фактор «банкротство»;</li>
 *     <li>BANKRUPT - признан банкротом, открыто конкурсное производство: стоп-фактор «банкротство»;</li>
 *     <li>LIQUIDATION - принято решение о ликвидации (ЕГРЮЛ): стоп-фактор «ликвидация».</li>
 * </ul>
 */
public enum EfrsbEventKind {
    INTENT,
    OBSERVATION,
    BANKRUPT,
    LIQUIDATION
}
