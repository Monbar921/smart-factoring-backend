package ru.smart.factoring.backend.factoring.scoring;

import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvSource;

import java.time.LocalDate;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Стоп-факторы на фактических значениях статусов ЕГРЮЛ и стадий дел из events.csv (п. 4.1).
 */
class StopFactorsTest {

    @ParameterizedTest(name = "{0} | {1} | {2} → {3}")
    @CsvSource(delimiter = '|', nullValues = "-", value = {
            "Юридическое лицо признано несостоятельным (банкротом) и в отношении него открыто конкурсное производство | Конкурсное производство | - | BANKRUPTCY",
            "В отношении юридического лица в деле о несостоятельности (банкротстве) введено наблюдение | Наблюдение | - | BANKRUPTCY",
            "В отношении юридического лица в деле о несостоятельности (банкротстве) введено внешнее управление | Внешнее управление | - | BANKRUPTCY",
            "В отношении юридического лица возбуждено производство по делу о несостоятельности (банкротстве) | - | - | BANKRUPTCY",
            "Ликвидировано на основании решения суда о признании его несостоятельным (банкротом) | Производство по делу завершено | 2026-06-23 | LIQUIDATION",
            "Юридическое лицо находится в стадии ликвидации | - | - | LIQUIDATION",
            "Регистрирующим органом принято решение о предстоящем исключении юридического лица из ЕГРЮЛ (наличие в ЕГРЮЛ сведений о юридическом лице, в отношении которых внесена запись о недостоверности) | - | - | EXCLUSION",
            "Юридическое лицо прекращено в связи с исключением из ЕГРЮЛ (наличие в ЕГРЮЛ сведений о юридическом лице, в отношении которых внесена запись о недостоверности) | - | - | EXCLUSION",
            "Действующее | Производство по делу прекращено | 2020-08-27 | -",
            "Действующее | Наблюдение | - | BANKRUPTCY",
            "Действующее | Наблюдение | 2025-01-10 | -",
            "Юридическое лицо находится в процессе реорганизации в форме преобразования | - | - | -",
            "Юридическим лицом принято решение об изменении места нахождения | - | - | -",
            "- | - | - | -"})
    void classifiesStatuses(final String status, final String stage, final LocalDate endDate, final StopFactors.StopFactor expected) {
        assertThat(StopFactors.classify(status, stage, endDate)).isEqualTo(expected);
    }
}
